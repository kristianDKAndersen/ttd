const toggle = (h: Harness, id: string) => $('.row-toggle', h.row(id))
const act = (h: Harness, id: string, which: 'trash' | 'play' | 'check') => $(`.act.${which}`, h.row(id))
const expand = async (h: Harness, id: string) => {
  click(toggle(h, id))
  await flush()
}
const openForm = async () => {
  click($('.add'))
  await flush()
}
const names = (h: Harness) => h.titles().map((t) => t.replace('task ', ''))

/** Full pointer drag of row `id` from its toggle to y, releasing there. */
const rowY = (i: number) => i * 40 + 10
function drag(h: Harness, id: string, ys: number[], release = true) {
  const from = toggle(h, id)
  const i = h.rows().indexOf(h.row(id))
  pointer(from, 'pointerdown', 10, rowY(i))
  for (const y of ys) pointer(from, 'pointermove', 10, y)
  if (release) pointer(from, 'pointerup', 10, ys[ys.length - 1]!)
}

